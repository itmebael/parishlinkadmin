create index if not exists confirmation_records_parish_id_idx
  on public.confirmation_records using btree (parish_id);
create index if not exists confirmation_records_name_idx
  on public.confirmation_records using btree (name);

alter table public.confirmation_records enable row level security;

drop policy if exists "Read scoped confirmation records" on public.confirmation_records;
drop policy if exists "Create scoped confirmation records" on public.confirmation_records;
drop policy if exists "Update scoped confirmation records" on public.confirmation_records;
drop policy if exists "Delete scoped confirmation records" on public.confirmation_records;

create policy "Read scoped confirmation records"
on public.confirmation_records for select to authenticated
using (
  coalesce(auth.jwt() -> 'app_metadata' ->> 'role', auth.jwt() -> 'user_metadata' ->> 'role', '') = 'diocese'
  or (
    coalesce(auth.jwt() -> 'app_metadata' ->> 'role', auth.jwt() -> 'user_metadata' ->> 'role', '') = 'parish'
    and parish_id = public.current_staff_parish_id()
  )
);

create policy "Create scoped confirmation records"
on public.confirmation_records for insert to authenticated
