create table if not exists public.confirmation_records (
  id bigint generated by default as identity not null,
  year_confirm integer null,
  month_confirm character varying(20) null,
  date_baptism integer null,
  name character varying(255) null,
  age character varying(50) null,
  location character varying(255) null,
  location_baptism character varying(255) null,
  mother_name character varying(255) null,
  father_name character varying(255) null,
  godparents character varying(255) null,
  stipend character varying(100) null,
  minister character varying(255) null,
  created_at timestamp with time zone null default now(),
  parish_id uuid null,
  constraint confirmation_records_pkey primary key (id)
);

