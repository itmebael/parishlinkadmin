create table if not exists public.marriage_records (
  id bigint generated by default as identity not null,
  entry_no integer null,
  marriage_date date null,
  party_role text null,
  name_family_name text null,
  status text null,
  age integer null,
  origin_of_birth text null,
  residence text null,
  parents text null,
  witness_1 text null,
  witness_2 text null,
  witness_residence text null,
  minister text null,
  remarks text null,
  created_at timestamp with time zone null default now(),
  parish_id uuid null,
  constraint marriage_records_pkey primary key (id)
);

alter table public.marriage_records add column if not exists entry_no integer;
