create index if not exists marriage_records_parish_id_idx
  on public.marriage_records using btree (parish_id);
create index if not exists marriage_records_name_family_name_idx
  on public.marriage_records using btree (name_family_name);

alter table public.marriage_records enable row level security;

drop policy if exists "Read scoped marriage records" on public.marriage_records;
drop policy if exists "Create scoped marriage records" on public.marriage_records;
drop policy if exists "Update scoped marriage records" on public.marriage_records;
drop policy if exists "Delete scoped marriage records" on public.marriage_records;

create policy "Read scoped marriage records"
on public.marriage_records for select to authenticated
using (
  coalesce(auth.jwt() -> 'app_metadata' ->> 'role', auth.jwt() -> 'user_metadata' ->> 'role', '') = 'diocese'
  or (
    coalesce(auth.jwt() -> 'app_metadata' ->> 'role', auth.jwt() -> 'user_metadata' ->> 'role', '') = 'parish'
    and parish_id = public.current_staff_parish_id()
  )
);

create policy "Create scoped marriage records"
on public.marriage_records for insert to authenticated
with check (
  coalesce(auth.jwt() -> 'app_metadata' ->> 'role', auth.jwt() -> 'user_metadata' ->> 'role', '') = 'diocese'
  or (
    coalesce(auth.jwt() -> 'app_metadata' ->> 'role', auth.jwt() -> 'user_metadata' ->> 'role', '') = 'parish'
    and parish_id = public.current_staff_parish_id()
  )
);

create policy "Update scoped marriage records"
on public.marriage_records for update to authenticated
