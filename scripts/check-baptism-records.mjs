import assert from 'node:assert/strict';
import { fetchBaptismRecords, recordDate } from '../dist/assets/baptism-records.js';
const session = { role: 'parish', parish_id: 'parish-a', accessToken: 'test-token', email: 'admin@example.test' };
const calls = [];
const request = async (path, options) => { calls.push({ path, options }); return Array.from({ length: 26 }, (_, id) => ({ id, name: `Person ${id}` })); };
const result = await fetchBaptismRecords(request, session, { page: 2, search: 'Maria & Ana' });
const query = new URL(calls[0].path, 'https://example.test').searchParams;
assert.equal(query.get('parish_id'), 'eq.parish-a');
assert.equal(query.get('offset'), '50');
assert.equal(query.get('name'), 'ilike.%Maria & Ana%');
assert.ok(query.get('select').includes('month_batism,date_batism'));
assert.equal(calls[0].options.accessToken, session.accessToken);
assert.equal(result.rows.length, 25);
assert.equal(result.hasNext, true);
assert.equal((await fetchBaptismRecords(async () => [], session)).hasNext, false);
await assert.rejects(fetchBaptismRecords(request, { ...session, role: 'user' }), /Sign in/);
await assert.rejects(fetchBaptismRecords(request, { ...session, accessToken: '' }), /Sign in/);
let recordReads = 0;
const unresolved = async path => { if (path.includes('baptism_records')) recordReads++; return []; };
await assert.rejects(fetchBaptismRecords(unresolved, { ...session, parish_id: null }), /not linked/);
assert.equal(recordReads, 0, 'Never fetch an unscoped list when the parish is missing');
await fetchBaptismRecords(async (path, options) => {
  assert.equal(options.accessToken, session.accessToken);
  if (path.includes('/rpc/')) return [{ id: 'resolved-parish' }];
  assert.equal(new URL(path, 'https://example.test').searchParams.get('parish_id'), 'eq.resolved-parish');
  return [];
}, { ...session, parish_id: null });
await assert.rejects(fetchBaptismRecords(async () => { throw new Error('permission denied'); }, session), /permission denied/);
assert.equal(recordDate(2026, 'September', 20), 'September 20 2026');
assert.equal(recordDate(null, null, null), 'Not recorded');
assert.equal(recordDate(1950, null, null), '1950');
console.log('PASS: baptism schema mapping, scoped authenticated reads, parish resolution, pagination, search, missing values and error handling.');
